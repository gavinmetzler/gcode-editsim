//! Times the pipeline on a large program (M3.9): interpretation, then the
//! render buffer, and reports the peak memory where the system says it.
//!
//! ```text
//! cargo run --release -p bench -- [--blocks N] [--write FILE] [PROGRAM]
//! ```
//!
//! Without `PROGRAM`, a generated pocketing program of `N` blocks (default
//! 1 000 000) is used: zigzag rows of short feed moves joined by arcs,
//! layer after layer, with a tool change every ten layers. It fits the
//! shipped generic mill's travel and gives no diagnostics. `--write` saves
//! the generated program, to open it in the app.
//!
//! Always build with `--release`: a debug build is several times slower.

#![forbid(unsafe_code)]

use std::fmt::Write as _;
use std::path::PathBuf;
use std::process::ExitCode;
use std::time::Instant;

/// What to run.
#[derive(Debug, PartialEq)]
struct Args {
    blocks: usize,
    write: Option<PathBuf>,
    program: Option<PathBuf>,
}

/// Reads the command line (without the program name).
fn parse_args(args: impl IntoIterator<Item = String>) -> Result<Args, String> {
    let mut parsed = Args {
        blocks: 1_000_000,
        write: None,
        program: None,
    };
    let mut it = args.into_iter();
    while let Some(a) = it.next() {
        match a.as_str() {
            "--blocks" => {
                let n = it.next().ok_or("--blocks needs a number")?;
                parsed.blocks = n
                    .replace('_', "")
                    .parse()
                    .map_err(|_| format!("--blocks: {n:?} is not a whole number"))?;
            }
            "--write" => {
                parsed.write = Some(PathBuf::from(it.next().ok_or("--write needs a file")?))
            }
            other if other.starts_with("--") => return Err(format!("unknown option {other}")),
            _ if parsed.program.is_some() => return Err("only one program file".into()),
            _ => parsed.program = Some(PathBuf::from(a)),
        }
    }
    Ok(parsed)
}

/// A Fanuc milling program of at least `blocks` lines (it finishes the
/// row it is on), for the generic mill: rows of twenty 5 mm feed moves
/// across X 0..100, joined by R1 half circles, 100 rows 2 mm apart per
/// layer, with a tool change every ten layers.
fn generate(blocks: usize) -> String {
    let mut out = String::from(
        "%\nO1000 (GENERATED BY TOOLS/BENCH)\nG21 G90 G17 G54\nT1 M6\nS12000 M3\nG0 X0. Y0. Z5.\n",
    );
    let mut lines = 6;
    let mut layer = 0usize;
    while lines < blocks {
        layer += 1;
        let z = -0.1 * (layer % 50) as f64;
        let _ = write!(out, "G0 Z5.\nG0 X0. Y0.\nG1 Z{z:.3} F300.\n");
        lines += 3;
        let mut y = 0.0;
        for row in 0..100u32 {
            let even = row.is_multiple_of(2);
            for k in 0..20 {
                let x = if even { (k + 1) * 5 } else { (19 - k) * 5 };
                let _ = writeln!(out, "G1 X{x}. Y{y:.3} F2000.");
                lines += 1;
            }
            let xe = if even { 100 } else { 0 };
            y -= 2.0;
            let _ = writeln!(out, "G{} X{xe}. Y{y:.3} R1.", if even { 2 } else { 3 });
            lines += 1;
            if lines >= blocks {
                break;
            }
        }
        if layer.is_multiple_of(10) {
            let _ = writeln!(out, "T{} M6", 1 + layer / 10 % 5);
            lines += 1;
        }
    }
    out.push_str("G0 Z50.\nM30\n%\n");
    out
}

/// The process's peak memory in MB, where the system reports it (Linux).
fn peak_memory_mb() -> Option<u64> {
    let status = std::fs::read_to_string("/proc/self/status").ok()?;
    let line = status.lines().find(|l| l.starts_with("VmHWM:"))?;
    let kb: u64 = line.split_whitespace().nth(1)?.parse().ok()?;
    Some(kb / 1024)
}

fn run(args: &Args) -> Result<(), String> {
    let source = match &args.program {
        Some(path) => app_backend::files::read_program(path).map_err(|e| e.to_string())?,
        None => generate(args.blocks).into_bytes(),
    };
    if let Some(path) = &args.write {
        std::fs::write(path, &source).map_err(|e| format!("{}: {e}", path.display()))?;
    }
    let machine_text = app_backend::files::shipped_machine("generic_3axis_mill")
        .ok_or("the shipped mill is missing")?;
    let machine = app_backend::load_machine(machine_text).map_err(|e| e.to_string())?;
    let dialect = app_backend::load_dialect("fanuc").map_err(|e| e.to_string())?;

    let start = Instant::now();
    let program = interpreter::interpret(
        &source,
        "bench.nc",
        dialect.as_ref(),
        machine.as_ref(),
        interpreter::Options::default(),
    );
    let interpreted = start.elapsed();
    let start = Instant::now();
    let buffer = ir::encode_render_buffer(&program, ir::DEFAULT_TOLERANCE, |p| {
        machine.forward_kinematics(p).position
    })
    .map_err(|e| e.to_string())?;
    let encoded = start.elapsed();

    let lines = source.iter().filter(|&&b| b == b'\n').count();
    let segments: usize = program.channels.iter().map(|c| c.segments.len()).sum();
    println!(
        "{lines} lines ({:.1} MB), {segments} segments, {} diagnostics",
        source.len() as f64 / 1e6,
        program.diagnostics.len()
    );
    println!("interpret:     {:>8.0} ms", interpreted.as_secs_f64() * 1e3);
    println!(
        "render buffer: {:>8.0} ms ({:.1} MB)",
        encoded.as_secs_f64() * 1e3,
        buffer.len() as f64 / 1e6
    );
    match peak_memory_mb() {
        Some(mb) => println!("peak memory:   {mb:>8} MB"),
        None => println!("peak memory:   not reported on this system"),
    }
    Ok(())
}

fn main() -> ExitCode {
    match parse_args(std::env::args().skip(1)).and_then(|a| run(&a)) {
        Ok(()) => ExitCode::SUCCESS,
        Err(e) => {
            eprintln!("bench: {e}");
            ExitCode::FAILURE
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn strings(a: &[&str]) -> Vec<String> {
        a.iter().map(|s| (*s).to_owned()).collect()
    }

    #[test]
    fn reads_options() {
        assert_eq!(
            parse_args(strings(&["--blocks", "250_000", "--write", "out.nc"])),
            Ok(Args {
                blocks: 250_000,
                write: Some(PathBuf::from("out.nc")),
                program: None,
            })
        );
        assert_eq!(
            parse_args(strings(&["p.nc"])).map(|a| (a.blocks, a.program)),
            Ok((1_000_000, Some(PathBuf::from("p.nc"))))
        );
        assert!(parse_args(strings(&["--blocks", "lots"])).is_err());
        assert!(parse_args(strings(&["--fast"])).is_err());
        assert!(parse_args(strings(&["a.nc", "b.nc"])).is_err());
    }

    #[test]
    fn the_generated_program_has_the_size_asked_for_and_runs_cleanly() {
        let text = generate(5_000);
        let lines = text.lines().count();
        // At least the size asked for, finishing the row it is on.
        assert!((5_000..5_030).contains(&lines), "{lines}");
        let machine_text = app_backend::files::shipped_machine("generic_3axis_mill").expect("mill");
        let machine = app_backend::load_machine(machine_text).expect("loads");
        let dialect = app_backend::load_dialect("fanuc").expect("fanuc");
        let p = interpreter::interpret(
            text.as_bytes(),
            "t.nc",
            dialect.as_ref(),
            machine.as_ref(),
            interpreter::Options::default(),
        );
        assert!(p.diagnostics.is_empty(), "{:?}", p.diagnostics);
        let moves = p.channels[0]
            .segments
            .iter()
            .filter(|s| s.kind.is_motion())
            .count();
        assert!(moves > 4_900, "{moves}");
    }
}
